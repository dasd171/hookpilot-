#!/usr/bin/env python3
"""Generate the Python-reference fixtures the web demo's cross-implementation test compares against.

    python tools/gen_web_fixtures.py            # writes apps/web-demo/tests/fixtures/python_reference.json
                                                #    and apps/web-demo/tests/fixtures/engine_reference.json
    python tools/gen_web_fixtures.py --check    # exit 1 if a present fixture file is stale

Both files are gitignored and regenerated by `npm test` (package.json "pretest").

SIMULATION. The file is deterministic (no timestamps), so tests/integration/test_web_fixtures.py can
check it is up to date with the Python port. Contents:
  signals          hookpilot-synth-v1 samples + drawn params for every scenario x SIGNAL_SEEDS
  classifications  deterministic-baseline-v1 (firmware rules, default thresholds) streaming result,
                   reason, rule_trace, features, decision/trigger times for every scenario x CLASS_SEEDS
engine_reference.json: the tick engine (evidence_service.engine.run_scenario, a port of the firmware
controller + host rig) for every case of tools/xcompare.py cases(): 9 scenarios x armed/disarmed x seeds
1-20, fault injections and parameter overrides. Per case: the per-tick trace (delta-encoded: each line keeps
only the keys that changed) and the implementation-independent record cores (xcompare.record_core).
"""
from __future__ import annotations

import argparse
import json
import os
import sys

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), ".."))
sys.path.insert(0, os.path.join(ROOT, "services", "evidence-service"))
sys.path.insert(0, os.path.join(ROOT, "tools"))

from evidence_service.classifier import (CLASSIFIER_ID, FW_DEFAULTS, IMPLEMENTATION, Thresholds,  # noqa: E402
                                         classify)
from evidence_service.engine import run_scenario  # noqa: E402
from evidence_service.synth import GENERATOR_ID, SCENARIOS, generate  # noqa: E402
import xcompare  # noqa: E402

OUT = os.path.join(ROOT, "apps", "web-demo", "tests", "fixtures", "python_reference.json")
OUT_ENGINE = os.path.join(ROOT, "apps", "web-demo", "tests", "fixtures", "engine_reference.json")
SIGNAL_SEEDS = (1, 42, 1337)
CLASS_SEEDS = tuple(range(1, 41))


def build() -> dict:
    th = Thresholds.defaults("fw")
    signals = []
    for sc in SCENARIOS:
        for seed in SIGNAL_SEEDS:
            sig = generate(sc, seed)
            signals.append({"scenario": sc, "seed": seed, "params": sig.params, "tension_n": sig.tension_n})
    classes = []
    for sc in SCENARIOS:
        for seed in CLASS_SEEDS:
            d = classify(generate(sc, seed).samples(), th)
            classes.append({"scenario": sc, "seed": seed, "result": d.result, "reason": d.reason,
                            "rule_trace": d.rule_trace, "decision_t_ms": d.decision_t_ms,
                            "trigger_t_ms": d.trigger_t_ms, "features": d.features})
    return {
        "label": "SIMULATION - Python reference for apps/web-demo/tests/cross_impl.test.ts",
        "command": "python tools/gen_web_fixtures.py",
        "generator": GENERATOR_ID, "classifier": CLASSIFIER_ID, "implementation": IMPLEMENTATION["fw"],
        "thresholds": FW_DEFAULTS, "signal_seeds": list(SIGNAL_SEEDS), "class_seeds": list(CLASS_SEEDS),
        "signals": signals, "classifications": classes,
    }


def build_engine() -> dict:
    runs = []
    for c in xcompare.cases():
        r = run_scenario(c["scenario"], c["seed"], armed=c["armed"], injections=c["injections"],
                         overrides=c["overrides"], trace=True)
        runs.append(dict(c, id=xcompare.case_id(c), trace=xcompare.delta_encode(r.trace),
                         records=[xcompare.record_core(x) for x in r.records]))
    return {
        "label": "SIMULATION - Python tick-engine reference for apps/web-demo/tests/cross_impl.test.ts",
        "command": "python tools/gen_web_fixtures.py", "tolerance": xcompare.TOL,
        "trace_keys": list(xcompare.TRACE_KEYS), "runs": runs,
    }


def dumps(d: dict) -> str:
    return json.dumps(d, separators=(",", ":")) + "\n"


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    ap.add_argument("--out", default=OUT)
    ap.add_argument("--out-engine", default=OUT_ENGINE)
    a = ap.parse_args()
    files = ((a.out, build), (a.out_engine, build_engine))
    if a.check:
        rc = 0
        for path, fn in files:
            if not os.path.exists(path):
                print(f"{path} not present (generated on demand by `npm test` in apps/web-demo)")
                continue
            if open(path, encoding="utf-8").read() != dumps(fn()):
                print(f"{path} is stale; run python tools/gen_web_fixtures.py")
                rc = 1
            else:
                print(f"{path} up to date")
        return rc
    for path, fn in files:
        text = dumps(fn())
        os.makedirs(os.path.dirname(path), exist_ok=True)
        with open(path, "w", encoding="utf-8", newline="\n") as f:
            f.write(text)
        print(f"wrote {path} ({len(text)} bytes)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
