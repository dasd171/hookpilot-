export class HookPilotEngine {
  readonly seed: number;
  readonly epochMs: number;
  readonly config: EngineConfig;
  readonly logger = new EventLogger();
  readonly log: LogLine[] = [];
  readonly chart: ChartPoint[] = [];
  readonly stateHistory: Transition[] = [];
  /** per-tick trace of the last run started with { trace: true } */
  trace: TraceLine[] = [];
  /** engine clock (ms since construction) */
  t = 0;
  private rig: Rig;
  private rigBase = 0;
  private idle: IdleSource;
  private idRng: Mulberry32;
  private counter = 0;
  private run: RunState | null = null;
  private runCfg: EngineConfig;
  private listeners = new Set<(e: HookPilotEvent) => void>();
  private transCursor = 0;
  private recCursor = 0;
  private scenarioMeta: { scenario: SynthScenario; seed: number } | null = null;

  constructor(opts: EngineOptions) {
    this.seed = opts.seed | 0;
    this.epochMs = opts.epochMs ?? DEFAULT_EPOCH_MS;
    this.config = cloneConfig(opts.config ?? defaultConfig());
    this.runCfg = this.config;
    this.idle = new IdleSource(this.seed);
    this.idRng = new Mulberry32((this.seed ^ 0x51ed27) | 0);
    this.rig = this.newRig(cloneConfig(this.config), [], false);
    this.rig.ctl.begin();
    this.say('info', 'Engine booted (SIMULATION). State IDLE, disarmed. No hardware connected.');
  }

  // ------------------------------------------------------------------ public API
  get events(): HookPilotEvent[] {
    return this.logger.records;
  }
  get state(): MachineState {
    return this.rig.ctl.state;
  }
  get armed(): boolean {
    return this.rig.ctl.safety.armed;
  }
  get busy(): boolean {
    return this.run !== null || this.rig.ctl.ev !== null;
  }
  onEvent(fn: (e: HookPilotEvent) => void): () => void {
    this.listeners.add(fn);
    return () => this.listeners.delete(fn);
  }
  /** UI sliders: take effect from the next scenario run (each run builds its rig from this config). */
  setTriggerThreshold(n: number) {
    this.config.classifier.trigger_delta_n = n;
  }
  setForceLimit(n: number) {
    this.config.safety.retrieval_force_limit_n = n;
  }

  arm(): { ok: boolean; reason: string } {
    const r = this.rig.ctl.requestArm();
    this.collect();
    if (!r.ok) return this.refuse(`Arm refused: ${r.reason}.`);
    this.say('info', 'Automation ARMED (simulated). Safety controller still arbitrates every actuation.');
    return r;
  }

  disarm(): { ok: boolean; reason: string } {
    this.rig.ctl.requestDisarm();
    this.collect();
    this.say('info', 'Automation DISARMED.');
    return { ok: true, reason: 'disarmed' };
  }

  startScenario(name: SynthScenario, seed: number = this.seed, opts: RunOptions = {}): { ok: boolean; reason: string } {
    if (this.state === 'SAFE_STOP') return this.refuse('Scenario refused: system is in SAFE_STOP. Reset first.');
    if (this.busy) return this.refuse('Scenario refused: another scenario/cycle is still running.');
    const signal = generateScenario(name, seed | 0);
    const injs = (opts.injections ?? []).map(parseInjection);
    const cfg = applyOverrides(this.config, opts.overrides);
    const armAtStart = opts.armed ?? this.armed;
    // fresh rig per run: boot at local t=0 (firmware sim_harness.cpp runScenario)
    this.rigBase = this.t;
    this.runCfg = cfg;
    this.rig = this.newRig(cfg, signal.tension, injs.some((i) => i.kind === 'watchdog_reset'));
    const sched: Injection[] = [];
    const fa = signal.params.fault_after_retrieval_start_ms;
    if ((name === 'motor_stall' || name === 'comm_loss') && fa !== undefined && fa >= 0) sched.push({ kind: name, atMs: fa, relRetrieval: true, value: null });
    for (const i of injs) if (i.kind !== 'watchdog_reset') sched.push(i);
    this.run = { signal, rig: this.rig, k: 0, armAtStart, sched, done: sched.map(() => false), retrievalSeen: false, retrievalStart: 0, firstRecord: this.logger.records.length, trace: opts.trace ? [] : null };
    this.scenarioMeta = { scenario: name, seed: seed | 0 };
    if (opts.trace) this.trace = this.run.trace!;
    this.rig.ctl.begin();
    this.collect();
    this.say('info', `Scenario "${name}" started (seed ${seed | 0}, ${signal.durationMs} ms ${signal.generator} signal).`);
    return { ok: true, reason: 'started' };
  }

  /** Operator "Reset to safe state": stop + disarm (closing any open event), abort a run, explicit reset. */
  resetToSafe(): { ok: boolean; reason: string } {
    const ctl = this.rig.ctl;
    if (ctl.state === 'SAFE_STOP') {
      const r = ctl.requestReset();
      this.collect();
      if (!r.ok) return this.refuse(`Reset blocked: ${r.reason}. Wait until they clear.`);
      this.say('info', 'Reset accepted: faults cleared. State IDLE, disarmed.');
      return r;
    }
    ctl.requestDisarm();
    if (this.run) {
      this.say('warn', `Scenario "${this.run.signal.scenario}" aborted by operator reset.`);
      this.endRun(false);
    }
    const r = ctl.requestReset();
    this.collect();
    this.say('info', 'Reset to safe state: actuators stopped, disarmed, IDLE.');
    return r.ok ? r : { ok: true, reason: 'reset' };
  }

  /** Advance one 20 ms tick (one harness step while a scenario runs). */
  step(): void {
    const run = this.run;
    const rig = this.rig;
    rig.step();
    if (run) {
      if (run.k === 0 && run.armAtStart) {
        const a = rig.ctl.requestArm();
        if (!a.ok) this.say('warn', `[SIMULATION] arm refused: ${a.reason}`);
      }
      const now = rig.now;
      if (rig.ctl.state === 'RETRIEVE' && !run.retrievalSeen) {
        run.retrievalSeen = true;
        run.retrievalStart = now;
      }
      const applied: string[] = [];
      run.sched.forEach((inj, q) => {
        if (run.done[q]) return;
        const fire = inj.relRetrieval ? run.retrievalSeen && now - run.retrievalStart >= inj.atMs : now >= inj.atMs;
        if (!fire) return;
        run.done[q] = true;
        rig.apply(inj);
        applied.push(inj.kind);
      });
      if (run.trace) run.trace.push(rig.traceLine(run.k, 'tick', applied));
      run.k++;
      if (run.k >= run.signal.tension.length) this.endRun(true);
    }
    this.collect();
    const s = rig.ctl.sample;
    this.chart.push({ t: this.t, x: s.valid ? s.x : NaN, baseline: s.baseline, state: rig.ctl.state });
    if (this.chart.length > 500) this.chart.shift();
    this.t += DT_MS;
  }

  stepN(n: number) {
    for (let i = 0; i < n; i++) this.step();
  }

  snapshot(): EngineSnapshot {
    const ctl = this.rig.ctl;
    const s = ctl.sample;
    const L = this.runCfg.safety;
    const records = this.logger.records;
    const c: Counters = { events: records.length, confirmed: 0, rejected: 0, no_event: 0, hook_set_cycles: 0, retrievals_completed: 0, safety_stops: 0, denied: 0 };
    for (const r of records) {
      const res = r.classification.result;
      if (res === 'bite_candidate_confirmed') c.confirmed++;
      else if (res === 'no_event') c.no_event++;
      else c.rejected++;
      if (r.outcome.milestones.hook_set_completed) c.hook_set_cycles++;
      if (r.outcome.milestones.retrieval_completed) c.retrievals_completed++;
      if (r.safety.decision === 'safe_stop') c.safety_stops++;
      if (r.safety.decision === 'deny' && res === 'bite_candidate_confirmed') c.denied++;
    }
    const tel = (a: 'hook_set' | 'retrieval'): ActuatorTelemetry => {
      const f = a === 'hook_set' ? this.rig.hook.fb : this.rig.retrieval.fb;
      return { actuator: a, position: f.position, current_a: f.current_a, status: f.status, active: f.active };
    };
    const hbOk = this.rig.comm.up && this.rig.now - this.rig.comm.lastHb <= L.comm_timeout_ms;
    const run = this.run;
    return {
      t_ms: this.t,
      state: ctl.state,
      armed: ctl.safety.armed,
      tension_n: s.valid ? s.x : null,
      baseline_n: s.baseline,
      delta_n: s.delta,
      rate_n_per_s: s.rate,
      sensor_health: s.health,
      detector_phase: ctl.det.open ? 'candidate' : ctl.awaitingRearm ? 'refractory' : 'ready',
      scenario: run ? { name: run.signal.scenario as SynthScenario, seed: run.signal.seed, progress: Math.min(1, run.k / run.signal.tension.length) } : null,
      live_faults: faultList(ctl.safety.active),
      latched_faults: faultList(ctl.safety.latched),
      interlocks: {
        armed: ctl.safety.armed,
        e_stop_clear: !this.rig.estop,
        sensor_valid: s.valid,
        comm_ok: hbOk,
        tension_below_hard_max: !s.valid || s.raw <= L.hard_max_tension_n,
        tension_below_force_limit: !s.valid || s.raw <= L.retrieval_force_limit_n,
        supply_ok: this.rig.voltage >= L.undervoltage_v,
        actuators_idle: !this.rig.hook.fb.active && !this.rig.retrieval.fb.active,
        no_latched_faults: ctl.safety.latched === 0,
      },
      hook_set: tel('hook_set'),
      retrieval: tel('retrieval'),
      heartbeat_ok: hbOk,
      counters: c,
    };
  }

  // ------------------------------------------------------------------ internals
  private newRig(cfg: EngineConfig, signal: ArrayLike<number>, watchdog: boolean): Rig {
    const rig = new Rig(cfg, signal, this.idle, watchdog);
    this.transCursor = 0;
    this.recCursor = 0;
    return rig;
  }

  /** End of the scenario window (firmware harness): disarm if an event is open; no_event summary if nothing was logged. */
  private endRun(normal: boolean) {
    const run = this.run!;
    const ctl = run.rig.ctl;
    if (normal) {
      if (ctl.ev) ctl.requestDisarm();
      if (this.logger.records.length + this.pendingRecords() === run.firstRecord) ctl.logNoEventSummary();
      if (run.trace) {
        this.collect();
        run.trace.push(run.rig.traceLine(run.signal.tension.length, 'end', []));
      }
    }
    // the scenario's injected faults end with the scenario signal (the rig continues on idle water)
    run.rig.comm.hbLost = false;
    run.rig.sensor.clearFaults();
    this.say('info', `Scenario "${run.signal.scenario}" finished.`);
    this.run = null;
  }

  private pendingRecords(): number {
    return this.rig.ctl.events.length - this.recCursor;
  }

  /** Seal new controller records into the hash chain and mirror new transitions into the UI log. */
  private collect() {
    const ctl = this.rig.ctl;
    while (this.transCursor < ctl.transitions.length) {
      const tr = ctl.transitions[this.transCursor++];
      this.stateHistory.push(tr);
      this.say(tr.to === 'SAFE_STOP' ? 'error' : 'info', `${tr.from} -> ${tr.to}: ${tr.reason}`);
    }
    while (this.recCursor < ctl.events.length) {
      const ev = ctl.events[this.recCursor++];
      const sealed = this.logger.append(this.toRecord(ev));
      this.say(ev.decision === 'safe_stop' ? 'error' : 'info', `Event ${sealed.event_id} logged: ${ev.result}, safety ${ev.decision}, ${ev.stopReason}.`);
      for (const fn of this.listeners) fn(sealed);
    }
  }

  private toRecord(ev: OpenEvent): Omit<HookPilotEvent, 'integrity'> {
    this.counter++;
    const id = `${DEVICE_ID}-${String(this.counter).padStart(6, '0')}-${this.idRng.nextU32().toString(16).padStart(8, '0')}`;
    const meta = this.scenarioMeta;
    const th = this.runCfg.classifier;
    const L = this.runCfg.safety;
    const base = this.epochMs + this.rigBase;
    const sensor: HookPilotEvent['sensor_data'] = {
      sample_rate_hz: SAMPLE_RATE_HZ,
      units: 'N',
      samples: ev.samples.map(([t, x]) => [t, x] as [number, number]),
      raw_data_ref: null,
      raw_data_sha256: null,
    };
    if (ev.invalidOmitted) sensor.invalid_samples_omitted = ev.invalidOmitted;
    return {
      schema_version: '1.0.0',
      event_id: id,
      device: { device_id: DEVICE_ID, firmware_version: FIRMWARE_VERSION, hardware_revision: 'none-simulated' },
      source: {
        mode: 'simulation',
        ...(meta ? { scenario: meta.scenario, seed: meta.seed, ground_truth_label: GROUND_TRUTH[meta.scenario], generator: GENERATOR_ID } : { ground_truth_label: null }),
      },
      timestamp: {
        start_utc: new Date(base + ev.startMs).toISOString(),
        end_utc: new Date(base + ev.endMs).toISOString(),
        monotonic_ms: this.rigBase + ev.startMs,
        clock_quality: 'host_clock_simulated',
      },
      calibration: { calibration_version: 'sim-uncalibrated-0', scale_n_per_count: 1, offset_counts: 0, calibrated_utc: null },
      sensor_data: sensor,
      features: { ...ev.features },
      classification: {
        result: ev.result,
        reason: ev.reason,
        rule_trace: [...ev.ruleTrace],
        classifier: CLASSIFIER_ID,
        implementation: CLASSIFIER_IMPLEMENTATION,
        thresholds: thresholdsRecord(th, L),
        ...(ev.triggerT !== null ? { trigger_t_ms: ev.triggerT } : {}),
        ...(ev.decisionT !== null ? { decision_t_ms: ev.decisionT } : {}),
      },
      safety: {
        decision: ev.decision,
        armed: ev.armed,
        interlocks: { ...ev.interlocks },
        faults: faultList(ev.faults),
        fault_latched_t_ms: { ...ev.faultLatchedT },
      },
      actuation: { requested: ev.requested.map((q) => ({ ...q, limit: { ...q.limit } })), feedback: ev.feedback.map((f) => ({ ...f })), simulated: true },
      outcome: {
        final_state: ev.finalState,
        stop_reason: ev.stopReason,
        milestones: { bite_detected: ev.biteDetected, hook_set_completed: ev.hookSetCompleted, retrieval_completed: ev.retrievalCompleted, fish_landed: 'unknown' },
        test_outcome: 'not_evaluated',
      },
    };
  }

  private refuse(reason: string) {
    this.say('warn', reason);
    return { ok: false, reason };
  }

  private say(level: LogLine['level'], text: string) {
    this.log.push({ t_ms: this.t, level, text });
    if (this.log.length > 300) this.log.shift();
  }
}

/**
 * Headless helper: run one scenario exactly like `hookpilot_sim --scenario <s> --seed <n>` (one fresh rig,
 * signal length ticks, end-of-window handling). Returns the engine (records in .events, trace in .trace).
 */
export function runScenario(
  scenario: SynthScenario | ScenarioName,
  seed: number,
  opts: { armed?: boolean; epochMs?: number; config?: EngineConfig; maxTicks?: number; injections?: Array<string | Injection>; overrides?: Record<string, number>; trace?: boolean } = {},
): HookPilotEngine {
  const e = new HookPilotEngine({ seed, epochMs: opts.epochMs, config: opts.config });
  const r = e.startScenario(scenario, seed, { armed: opts.armed ?? true, injections: opts.injections, overrides: opts.overrides, trace: opts.trace });
  if (!r.ok) throw new Error(r.reason);
  const max = opts.maxTicks ?? 5000;
  let n = 0;
  while (e.busy && n < max) {
    e.step();
    n++;
  }
  if (e.busy) throw new Error(`scenario ${scenario} did not finish within ${max} ticks`);
  return e;
}
