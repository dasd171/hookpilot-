export const INJECTION_KINDS = [
  'sensor_disconnect',
  'sensor_nan',
  'sensor_out_of_range',
  'sensor_stuck',
  'over_tension',
  'motor_stall',
  'encoder_loss',
  'hook_jam',
  'comm_loss',
  'link_down',
  'undervoltage',
  'estop',
  'over_temp',
  'watchdog_reset',
] as const;
export type InjectionKind = (typeof INJECTION_KINDS)[number];

/** "<kind>@<t_ms|retrieval+ms>[:value]" (docs/engine-spec.md "Fault injection"). */
export interface Injection {
  kind: InjectionKind;
  atMs: number;
  relRetrieval: boolean;
  value: number | null;
}

export function parseInjection(spec: string | Injection): Injection {
  if (typeof spec !== 'string') return spec;
  const at = spec.indexOf('@');
  const kind = (at >= 0 ? spec.slice(0, at) : spec) as InjectionKind;
  if (!INJECTION_KINDS.includes(kind)) throw new Error(`unknown injection kind ${kind}`);
  const inj: Injection = { kind, atMs: 0, relRetrieval: false, value: null };
  if (at >= 0) {
    let rest = spec.slice(at + 1);
    const colon = rest.indexOf(':');
    if (colon >= 0) {
      inj.value = Number(rest.slice(colon + 1));
      rest = rest.slice(0, colon);
    }
    if (rest.startsWith('retrieval+')) {
      inj.relRetrieval = true;
      rest = rest.slice('retrieval+'.length);
    }
    inj.atMs = Number(rest);
    if (rest === '' || !Number.isFinite(inj.atMs)) throw new Error(`bad time in injection ${spec}`);
  }
  return inj;
}

