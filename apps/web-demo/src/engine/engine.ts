/** Replays a signal sample by sample with injectable faults; NaN = no reading. Falls back to idle water. */
export class MockSensor {
  idx = 0;
  additive = 0;
  disconnect = false;
  nan = false;
  oor = false;
  stuck = false;
  override = false;
  oorValue = 60;
  overrideValue = 0;
  haveStuck = false;
  stuckValue = 0;
  constructor(
    public sig: ArrayLike<number>,
    public fallback: IdleSource | null = null,
  ) {}

  read(now: number): number {
    let v: number;
    if (this.idx < this.sig.length) v = this.sig[this.idx++];
    else if (this.fallback) v = this.fallback.sample(now);
    else return NaN;
    v += this.additive;
    if (this.override) v = this.overrideValue;
    if (this.stuck) {
      if (!this.haveStuck) {
        this.stuckValue = v;
        this.haveStuck = true;
      }
      v = this.stuckValue;
    }
    if (this.disconnect || this.nan) return NaN;
    if (this.oor) v = this.oorValue;
    return v;
  }
  clearFaults() {
    this.disconnect = this.nan = this.oor = this.stuck = this.override = false;
    this.haveStuck = false;
  }
}

