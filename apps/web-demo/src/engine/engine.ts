/** Port of firmware SimRig (clock, mocks, controller) plus the harness step bookkeeping. */
export class Rig {
  now = 0;
  private first = true;
  readonly sensor: MockSensor;
  readonly hook: MockHook;
  readonly retrieval: MockRetrieval;
  readonly comm = new MockComm();
  voltage = 11.4;
  temperature = 25.0;
  estop = false;
  lastLoad = 0;
  readonly ctl: Controller;
  private cur = { req: 0, trans: 0, rec: 0 };

  constructor(
    readonly cfg: EngineConfig,
    signal: ArrayLike<number>,
    fallback: IdleSource | null,
    readonly watchdogReset = false,
  ) {
    this.sensor = new MockSensor(signal, fallback);
    this.hook = new MockHook(cfg.actuators.hook_set_position_tol_mm);
    this.retrieval = new MockRetrieval(cfg.coupling);
    this.ctl = new Controller(cfg, this);
  }

  step() {
    if (!this.first) this.now += DT_MS;
    this.first = false;
    const C = this.cfg.coupling;
    let load = 0;
    if (this.hook.fb.active) load += C.hook_set_line_load_n;
    if (this.retrieval.fb.active) load += C.retrieval_line_load_n;
    this.sensor.additive = load;
    this.lastLoad = load;
    this.retrieval.loadN = this.ctl.sample.x;
    this.ctl.tick();
  }

  apply(inj: Injection) {
    const v = inj.value;
    const s = this.sensor;
    switch (inj.kind) {
      case 'sensor_disconnect': s.disconnect = true; break;
      case 'sensor_nan': s.nan = true; break;
      case 'sensor_out_of_range': s.oor = true; s.oorValue = v ?? 60; break;
      case 'sensor_stuck': s.stuck = true; s.haveStuck = false; break;
      case 'over_tension': s.override = true; s.overrideValue = v ?? 25; break;
      case 'motor_stall': this.retrieval.stall = true; break;
      case 'encoder_loss': this.retrieval.encLoss = true; break;
      case 'hook_jam': this.hook.jam = true; break;
      case 'comm_loss': this.comm.hbLost = true; break;
      case 'link_down': this.comm.up = false; break;
      case 'undervoltage': this.voltage = v ?? 10.2; break;
      case 'estop': this.estop = true; break;
      case 'over_temp': this.temperature = v ?? 75; break;
      case 'watchdog_reset': break;
    }
  }

  traceLine(k: number, phase: 'tick' | 'end', injected: string[]): TraceLine {
    const c = this.ctl;
    const s = c.sample;
    const fbT = (f: ActuatorFeedback): FeedbackTrace => ({ pos: f.position, cur: f.current_a, active: f.active, at_target: f.at_target, pos_valid: f.position_valid, status: f.status });
    const cmds = c.requestLog.slice(this.cur.req).map((x) => ({ ...x }));
    this.cur.req = c.requestLog.length;
    const trans = c.transitions.slice(this.cur.trans).map((x) => ({ t: x.t_ms, from: x.from, to: x.to, reason: x.reason }));
    this.cur.trans = c.transitions.length;
    const recs = c.events.length - this.cur.rec;
    this.cur.rec = c.events.length;
    return {
      k,
      phase,
      t: this.now,
      state: c.state,
      armed: c.safety.armed,
      raw: Number.isFinite(s.raw) ? s.raw : null,
      valid: s.valid,
      health: s.health,
      x: s.x,
      baseline: s.baseline,
      delta: s.delta,
      load_n: this.lastLoad,
      hook: fbT(this.hook.fb),
      retr: fbT(this.retrieval.fb),
      hb_ms: this.comm.lastHb,
      latched: faultList(c.safety.latched),
      active: faultList(c.safety.active),
      cmds,
      trans,
      injected,
      records: recs,
    };
  }
}

