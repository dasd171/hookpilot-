/**
 * HookPilot engine - SIMULATION ONLY. Pure TS (no DOM / React). Fixed 20 ms ticks (50 Hz).
 *
 * Tick-for-tick port of the firmware control core and host rig (ground truth), identical to the Python
 * reference engine (evidence_service.engine):
 *   Controller  <- firmware/src/core/controller.cpp  (state machine, records)
 *   safety.ts   <- firmware/src/core/safety_controller.cpp
 *   actuators.ts, MockSensor, MockComm <- firmware/host/mocks.{h,cpp}
 *   Rig + runOne() <- firmware/host/sim_harness.cpp  (line load, injections, end of window)
 * The normative description is docs/engine-spec.md. tests/cross_impl.test.ts compares this engine's per-tick
 * trace and records with fixtures generated by the Python port (tools/gen_web_fixtures.py).
 *
 * States: IDLE, MONITOR, CANDIDATE, CONFIRM, HOOK_SET, RETRIEVE, VERIFY, SAFE_STOP. IDLE = disarmed: the
 * detector still observes and logs (observation only), nothing is ever requested. SAFE_STOP exits only via an
 * explicit reset with faults cleared, into IDLE (disarmed). A completed cycle ends in IDLE, disarmed.
 *
 * HookPilotEngine wraps a Rig for the interactive demo: every scenario run gets a fresh rig (boot at local
 * t=0, arm after the first tick when the operator had armed), exactly like `hookpilot_sim`; between runs the
 * rig keeps ticking on synthetic idle water.
 */
